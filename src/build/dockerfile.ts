import type {WayuseClient} from "wayuse"
import {SERVER_TARBALL} from "./npm-package.ts"

type Resolved = WayuseClient.Config

export interface BuildOptions {
    /** A @wayuse/server tarball to install in place of the one on npm. */
    serverTarball?: string
    /** The values of console.vars, with the defaults among them. Default: the defaults alone. */
    vars?: Record<string, string>
    /** Whether the console's scripts and the packages beside them are made small. Default: true. */
    terser?: boolean
    /** The directory of the configuration, as Docker Compose names its project after it. The scripts name the image and the volume the same way. Default: "wayuse". */
    project?: string
}

const UBUNTU = "ubuntu:26.04"

// The screen itself: sway (headless) served by wayvnc, with grim and wl-clipboard for the server's APIs.
const SCREEN_PACKAGES = ["dbus-daemon", "fontconfig", "grim", "sway", "wayvnc", "wl-clipboard"]

// tini is PID 1 in the image itself, so zombies are reaped even when `docker run` has no --init.
const BASE_PACKAGES = ["ca-certificates", "curl", "procps", "tini", "tzdata", "xz-utils"]

const headerOf = (config: Resolved): string => `
# Generated by @wayuse/build ${config.wayuse.build.version}. Edit ${config.wayuse.build.config} and build again.
FROM ${UBUNTU}
`.trim()

// Each apt layer refreshes the index itself: a cached earlier layer may hold one too old to install from.
const aptInstall = (packages: string[]): string => `
RUN apt-get update && \\
    DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends \\
${packages.map(name => `        ${name}`).join(" \\\n")}
`.trim()

const nodeInstall = (version: string): string => {
    const dir = `/opt/node-v${version}-linux-\${ARCH}`
    return `
RUN ARCH="$(uname -m | sed -e s/x86_64/x64/ -e s/aarch64/arm64/)" && \\
    curl -sSf "https://nodejs.org/dist/v${version}/node-v${version}-linux-\${ARCH}.tar.xz" | tar Jxf - -C /opt && \\
    ln -s "${dir}/bin/node" "${dir}/bin/npm" "${dir}/bin/npx" /usr/local/bin/
`.trim()
}

// The channel's current .deb: the version is whatever Google serves when this layer is built.
const chromeInstall = (channel: string): string => `
RUN curl -sSfo /tmp/chrome.deb "https://dl.google.com/linux/direct/google-chrome-${channel}_current_$(dpkg --print-architecture).deb" && \\
    apt-get update && \\
    DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends /tmp/chrome.deb && \\
    rm -f /tmp/chrome.deb
`.trim()

// The user Ubuntu ships holds uid 1000 and gives way: a fixed uid lets a host match the owner of a volume.
const USER_SETUP = `
RUN userdel -r ubuntu && \\
    useradd -m -u 1000 -s /bin/bash wayuse && \\
    install -d -m 700 -o wayuse -g wayuse /run/wayuse && \\
    install -d -o wayuse -g wayuse /home/wayuse/.config
`.trim()

// The build fails on a name tzdata does not have, rather than leaving a dangling link.
const timezoneSetup = (timezone: string): string => `
RUN test -f /usr/share/zoneinfo/${timezone} && \\
    ln -sf /usr/share/zoneinfo/${timezone} /etc/localtime
`.trim()

// Copied ahead of the rest of rootfs/, so a changed setting does not install the packages again.
const npmInstall = (tarball: boolean): string => `
COPY ${["package.json", ...(tarball ? [SERVER_TARBALL] : [])].map(name => `rootfs/opt/wayuse/${name}`).join(" ")} /opt/wayuse/
RUN npm install --prefix /opt/wayuse --omit=dev --no-audit --no-fund && \\
    npm cache clean --force
`.trim()

/** The port the server listens on in the image. */
export const PORT = 9580

// Fixed paths, so that `docker exec` reaches the same sway as the processes started here.
export const RUNTIME_ENV = [
    "XDG_RUNTIME_DIR=/run/wayuse",
    "WAYLAND_DISPLAY=wayland-1",
    "SWAYSOCK=/run/wayuse/sway.sock",
]

/** The processes the container keeps running, in the order they start. */
export const commandsOf = (config: Resolved): string[] => [
    "/opt/wayuse/bin/dbus-start.sh",
    "/opt/wayuse/bin/sway-start.sh",
    "/opt/wayuse/bin/wayvnc-start.sh",
    ...(config.apps.chrome ? ["/opt/wayuse/bin/chrome-start.sh"] : []),
    ...(config.apps.redir ? ["/opt/wayuse/bin/redir-start.sh"] : []),
    "/opt/wayuse/bin/server-start.sh",
]

const runtimeOf = (config: Resolved): string => `
EXPOSE ${PORT}
USER wayuse
WORKDIR /home/wayuse
ENV ${RUNTIME_ENV.join(" ")}
ENTRYPOINT ${JSON.stringify(["/usr/bin/tini", "--"])}
CMD ${JSON.stringify(["/opt/wayuse/bin/supervise.sh", ...commandsOf(config)])}
`.trim()

/**
 * The Dockerfile, ordered so that a changed setting rebuilds as few layers as it can.
 */
export const dockerfileOf = (config: Resolved, options: BuildOptions = {}): string => {
    const {chrome, redir} = config.apps

    const steps = [
        headerOf(config),
        // What no setting changes comes first, then one layer per setting: Chrome ahead, so no other setting moves its version.
        aptInstall([...BASE_PACKAGES, ...SCREEN_PACKAGES]),
        chrome && chromeInstall(chrome.channel),
        nodeInstall(config.node.version),
        config.packages.length > 0 && aptInstall(config.packages),
        // After the packages, so turning it on or off installs none of them again.
        redir && aptInstall(["redir"]),
        USER_SETUP,
        timezoneSetup(config.timezone),
        // Last of the installs: the server is what changes most often while it is developed.
        npmInstall(options.serverTarball != null),
        "COPY rootfs/ /",
        runtimeOf(config),
    ]

    return steps.filter(step => step).join("\n\n") + "\n"
}
