// The start scripts that take values of the configuration. The other scripts are copied from assets/ as they are.

import type {WayuseClient} from "wayuse"
import {shellDefaultsOf} from "./shell-env.ts"
import {SWAY_CONFIG} from "./sway-config.ts"

type Resolved = WayuseClient.Config

// The line after the shebang, as in the other files the build generates.
const headerOf = (config: Resolved): string =>
    `# Generated by @wayuse/build ${config.wayuse.build.version}. Edit ${config.wayuse.build.config} and build again.`

// sway and wayvnc take the same number, which the container may be given.
const outputsOf = (config: Resolved): string =>
    "# screen.outputs of the configuration. One given to the container wins.\n" + shellDefaultsOf({WAYUSE_SCREEN_OUTPUTS: String(config.screen.outputs)})

/**
 * /opt/wayuse/bin/sway-start.sh
 */
export const swayStartOf = (config: Resolved): string => `
#!/bin/bash
${headerOf(config)}
# Starts sway with one headless output per screen: HEADLESS-1 and up.
set -eu

${outputsOf(config)}
export WLR_BACKENDS=headless WLR_RENDERER=pixman WLR_LIBINPUT_NO_DEVICES=1
export WLR_HEADLESS_OUTPUTS=$WAYUSE_SCREEN_OUTPUTS

# sway names its own socket: a name set beforehand would read as a compositor to connect to.
unset WAYLAND_DISPLAY

# sway takes the path in SWAYSOCK only while nothing is there.
rm -f "$SWAYSOCK"

exec sway -c ${SWAY_CONFIG}
`.trimStart()

/**
 * /opt/wayuse/bin/wayvnc-start.sh
 */
export const wayvncStartOf = (config: Resolved): string => `
#!/bin/bash
${headerOf(config)}
# Starts one wayvnc per output: HEADLESS-n listens on 127.0.0.1:590n.
set -eu

${outputsOf(config)}
# When one wayvnc ends the others go with it, so the supervisor brings all of them back together.
trap 'kill $(jobs -p) 2>/dev/null' EXIT
trap 'exit 143' TERM INT

until [ -S "$XDG_RUNTIME_DIR/$WAYLAND_DISPLAY" ]; do sleep 0.2; done

for n in $(seq "$WAYUSE_SCREEN_OUTPUTS"); do
    wayvnc --socket="$XDG_RUNTIME_DIR/wayvncctl-$n" --output="HEADLESS-$n" 127.0.0.1 "$((5900 + n))" &
done

wait -n
`.trimStart()

// Set by chrome-start.sh itself, ahead of apps.chrome.env.
export const CHROME_START_ENV: Record<string, string> = {DBUS_SESSION_BUS_ADDRESS: "unix:path=$XDG_RUNTIME_DIR/bus"}

const exportsOf = (env: Record<string, string>): string => Object.entries(env).map(([name, value]) => `export ${name}="${value}"\n`).join("")

/**
 * /opt/wayuse/bin/chrome-start.sh, for an image with Chrome.
 */
export const chromeStartOf = (config: Resolved): string => `
#!/bin/bash
${headerOf(config)}
# Starts Chrome on the sway session, with no window until a client opens one.
set -eu

profile=$HOME/.config/chrome

# Chrome alone does not look for the session bus in $XDG_RUNTIME_DIR by itself.
${exportsOf(CHROME_START_ENV)}
until [ -S "$XDG_RUNTIME_DIR/$WAYLAND_DISPLAY" ]; do sleep 0.2; done

# A lock left by a killed Chrome would refuse this start.
rm -f "$profile"/Singleton*

# The variables of apps.chrome.env reach this process alone. One given to the container wins.
${shellDefaultsOf(config.apps.chrome?.env ?? {})}
# --no-startup-window keeps Chrome running after its last window closes.
# Docker gives a container neither the namespaces of the sandbox nor a large /dev/shm. --no-sandbox and --disable-dev-shm-usage do without them.
exec google-chrome \\
    --ozone-platform=wayland \\
    --disable-gpu \\
    --password-store=basic \\
    --no-first-run \\
    --no-default-browser-check \\
    --remote-debugging-port=9222 \\
    --user-data-dir="$profile" \\
    --profile-directory=Default \\
    --no-startup-window \\
    --no-sandbox \\
    --disable-dev-shm-usage \\
    \${WAYUSE_USER_AGENT:+"--user-agent=$WAYUSE_USER_AGENT"}
`.trimStart()

/**
 * /opt/wayuse/bin/redir-start.sh, for an image with redir.
 */
export const redirStartOf = (config: Resolved): string => `
#!/bin/bash
${headerOf(config)}
# Starts one redir per port of apps.redir.ports. It listens on the port, and forwards to the address beside it.
set -eu

# When one redir ends the others go with it, so the supervisor brings all of them back together.
trap 'kill $(jobs -p) 2>/dev/null' EXIT
trap 'exit 143' TERM INT

# Each runs in the foreground, as a job of this script. A redir in the background would look ended.
${Object.entries(config.apps.redir?.ports ?? {}).map(([port, target]) => `redir -n :${port} ${target} &\n`).join("")}
wait -n
`.trimStart()
