import assert from "node:assert/strict"
import {readFileSync} from "node:fs"
import {mkdir, mkdtemp, readFile, readdir, rm, stat, writeFile} from "node:fs/promises"
import {tmpdir} from "node:os"
import {join} from "node:path"
import {describe, it} from "node:test"
import {DEFAULT_URL} from "../client/cli-api.ts"
import {DEFAULT_CONFIG, DEFAULT_HTDOCS, DEFAULT_PORT} from "../server/cli.ts"
import {resolveConfig} from "./config.ts"
import {generatedFilesOf, writeBuildDir} from "./files.ts"
import {APP_PACKAGES} from "./npm-package.ts"
import {shellDefaultsOf} from "./shell-env.ts"

const TITLE = "build/files.test.ts"

describe(TITLE, () => {
    const config = resolveConfig({
        node: {version: "24.11.1"},
        apps: {chrome: {channel: "beta", env: {LANGUAGE: "ja"}, policies: {AutoplayAllowlist: ["https://www.youtube.com"]}}},
        timezone: "Asia/Tokyo",
        screen: {width: 1920, height: 1080},
        packages: ["fonts-noto-cjk"],
        console: {signIn: "/sign-in/?next="},
    }, "wayuse.config.ts")

    it("puts each setting where it takes effect", () => {
        const files = generatedFilesOf(config)
        const dockerfile = files["Dockerfile"]!
        assert.match(dockerfile, /node-v24\.11\.1-linux-/)
        assert.match(dockerfile, /google-chrome-beta_current_/)
        assert.match(dockerfile, /zoneinfo\/Asia\/Tokyo \/etc\/localtime/)
        assert.match(dockerfile, /\n {8}fonts-noto-cjk\n/)
        assert.match(dockerfile, /chrome-start\.sh","\/opt\/wayuse\/bin\/server-start\.sh"\]\n$/)
        assert.match(files["rootfs/opt/wayuse/config/sway.conf"]!, /^output \* resolution 1920x1080$/m)
        assert.match(files["rootfs/opt/wayuse/config/sway.conf"]!, /^output HEADLESS-2 position 2432 0$/m)
        assert.match(files["rootfs/opt/wayuse/bin/chrome-start.sh"]!, /^export LANGUAGE=\$\{LANGUAGE:-'ja'\}$/m)
        assert.deepEqual(JSON.parse(files["rootfs/etc/opt/chrome/policies/managed/wayuse.json"]!), {AutoplayAllowlist: ["https://www.youtube.com"]})
        // Where the server reads it by default.
        assert.deepEqual(JSON.parse(files[`rootfs${DEFAULT_CONFIG}`]!), config)
        assert.deepEqual(JSON.parse(files["rootfs/opt/wayuse/htdocs/console/config.json"]!), {signIn: "/sign-in/?next="})
        assert.match(files["rootfs/opt/wayuse/.gitignore"]!, /^\*$/m)
    })

    it("leaves Chrome out of an image without it, and what only Chrome needs", () => {
        const files = generatedFilesOf(resolveConfig({}, "wayuse.config.ts"))
        assert.doesNotMatch(files["Dockerfile"]!, /chrome/)
        assert.equal(files["rootfs/opt/wayuse/bin/chrome-start.sh"], undefined)
        assert.equal(files["rootfs/opt/wayuse/bin/redir-start.sh"], undefined)
        assert.equal(files["rootfs/etc/opt/chrome/policies/managed/wayuse.json"], undefined)
        assert.equal(files["rootfs/opt/wayuse/htdocs/console/config.json"], "{}\n")
        assert.deepEqual(JSON.parse(files["rootfs/opt/wayuse/package.json"]!).dependencies, {"@wayuse/server": "^0.0.0"})
    })

    it("spaces the outputs apart for the widest screen", () => {
        const sway = generatedFilesOf(resolveConfig({screen: {maxWidth: 2560}}, "wayuse.config.ts"))["rootfs/opt/wayuse/config/sway.conf"]!
        assert.match(sway, /^output HEADLESS-2 position 3072 0$/m)
        assert.match(sway, /^output HEADLESS-8 position 21504 0$/m)
    })

    it("gives sway and wayvnc the number of screens, below what the container is given", () => {
        const files = generatedFilesOf(resolveConfig({screen: {outputs: 3}}, "wayuse.config.ts"))
        for (const name of ["sway-start.sh", "wayvnc-start.sh"]) {
            assert.match(files[`rootfs/opt/wayuse/bin/${name}`]!, /^export WAYUSE_SCREEN_OUTPUTS=\$\{WAYUSE_SCREEN_OUTPUTS:-'3'\}$/m, name)
        }
    })

    it("gives Chrome the address of the session bus", () => {
        const chrome = generatedFilesOf(config)["rootfs/opt/wayuse/bin/chrome-start.sh"]!
        assert.match(chrome, /^export DBUS_SESSION_BUS_ADDRESS="unix:path=\$XDG_RUNTIME_DIR\/bus"$/m)
    })

    it("names the configuration to edit in the headers", () => {
        const files = generatedFilesOf(resolveConfig({}, "chrome.config.ts"))
        assert.match(files["Dockerfile"]!, /^# Generated by .*\. Edit chrome\.config\.ts and build again\.\n/)
        assert.match(files["rootfs/opt/wayuse/config/sway.conf"]!, /^# Generated by .*\. Edit chrome\.config\.ts and build again\.\n/)
        assert.match(files["rootfs/opt/wayuse/bin/sway-start.sh"]!, /^#!\/bin\/bash\n# Generated by .*\. Edit chrome\.config\.ts and build again\.\n/)
    })

    // A missing backslash, or one after the last package, makes a Dockerfile that does not build.
    it("continues the line after every package but the last", () => {
        const dockerfile = generatedFilesOf(resolveConfig({packages: ["fonts-noto-cjk", "fonts-noto-core"]}, "wayuse.config.ts"))["Dockerfile"]!
        assert.match(dockerfile, /--no-install-recommends \\\n {8}fonts-noto-cjk \\\n {8}fonts-noto-core\n\n/)
    })

    it("installs redir and keeps it running, with a line for each port in its start script", () => {
        const files = generatedFilesOf(resolveConfig({apps: {redir: {ports: {9223: "127.0.0.1:9222", 18081: "host.docker.internal:18081"}}}}, "wayuse.config.ts"))
        const dockerfile = files["Dockerfile"]!
        assert.match(dockerfile, /\n {8}redir\n/)
        assert.match(dockerfile, /"\/opt\/wayuse\/bin\/redir-start\.sh","\/opt\/wayuse\/bin\/server-start\.sh"\]\n$/)
        const start = files["rootfs/opt/wayuse/bin/redir-start.sh"]!
        assert.match(start, /^redir -n :9223 127\.0\.0\.1:9222 &\nredir -n :18081 host\.docker\.internal:18081 &\n$/m)
    })

    it("installs what the server needs for Chrome beside the server", () => {
        const files = generatedFilesOf(config, {serverTarball: "server.tgz"})
        assert.deepEqual(JSON.parse(files["rootfs/opt/wayuse/package.json"]!).dependencies, {"@wayuse/server": "file:wayuse-server.tgz", "html-slim": "^0.5.0"})
    })

    // @wayuse/build does not depend on the server, so nothing but this test holds the two lists together.
    it("names for the applications exactly the server's optional peers, at the same ranges", () => {
        const server = JSON.parse(readFileSync(new URL("../../packages/server/package.json", import.meta.url), "utf8"))
        assert.deepEqual(Object.assign({}, ...Object.values(APP_PACKAGES)), server.peerDependencies)
        assert.deepEqual(Object.keys(server.peerDependenciesMeta), Object.keys(server.peerDependencies))
        for (const meta of Object.values(server.peerDependenciesMeta)) assert.deepEqual(meta, {optional: true})
    })

    // The three packages do not depend on one another, so nothing but this test holds their port together.
    it("listens in the image on the port the server and the client take by default", () => {
        const port = String(DEFAULT_PORT)
        assert.equal(new URL(DEFAULT_URL).port, port)
        assert.equal(generatedFilesOf(config)["Dockerfile"]!.match(/^EXPOSE (\d+)$/m)?.[1], port)

        const start = readFileSync(new URL("../../packages/build/assets/rootfs/opt/wayuse/bin/server-start.sh", import.meta.url), "utf8")
        assert.equal(start.match(/ --port=(\d+)$/m)?.[1], port)

        // The sample publishes the port under its own number, which is where the client's default looks.
        const sample = readFileSync(new URL("../../packages/build/sample/docker-compose.yml", import.meta.url), "utf8")
        assert.equal(sample.match(/^ +- "\$\{WAYUSE_PUBLISH:-127\.0\.0\.1:(\d+)\}:(\d+)"$/m)?.slice(1).join(), `${port},${port}`)
    })

    // A settings-only change must rebuild nothing above the COPY.
    it("copies the settings after every install", () => {
        const dockerfile = generatedFilesOf(config)["Dockerfile"]!
        const copy = dockerfile.indexOf("COPY rootfs/")
        assert.ok(copy > dockerfile.lastIndexOf("apt-get install"))
    })

    it("quotes an environment value so that the shell runs none of it", () => {
        assert.equal(shellDefaultsOf({A: "it's $(date) `id`"}), "export A=${A:-'it'\\''s $(date) `id`'}\n")
    })

    it("writes the pages with the default icon and title where none is given", async () => {
        const outdir = await mkdtemp(join(tmpdir(), "wayuse-"))
        try {
            await writeBuildDir(config, outdir)
            const monitor = await readFile(join(outdir, "rootfs", DEFAULT_HTDOCS, "console/monitor/index.html"), "utf8")
            assert.match(monitor, /<title>wayuse monitor<\/title>/)
            assert.match(monitor, /<span class="header-icon">🖥️<\/span>\n +<span class="header-title">wayuse<\/span>/)
        } finally {
            await rm(outdir, {recursive: true, force: true})
        }
    })

    it("writes the console's scripts as they were built where terser is off, and smaller where it is on", async () => {
        const built = await readFile(new URL("../../packages/build/dist/console/monitor.js", import.meta.url), "utf8")
        const outdir = await mkdtemp(join(tmpdir(), "wayuse-"))
        try {
            const script = join(outdir, "rootfs", DEFAULT_HTDOCS, "console/js/monitor.js")
            const vendor = join(outdir, "rootfs", DEFAULT_HTDOCS, "console/vendor/html-ele.js")

            await writeBuildDir(config, outdir, {terser: false})
            assert.equal(await readFile(script, "utf8"), built)
            const plain = await readFile(vendor, "utf8")

            await writeBuildDir(config, outdir)
            assert.ok((await readFile(script, "utf8")).length < built.length)
            assert.ok((await readFile(vendor, "utf8")).length < plain.length)
        } finally {
            await rm(outdir, {recursive: true, force: true})
        }
    })

    it("writes nothing for a browser into an image without the console", async () => {
        const bare = resolveConfig({console: false}, "wayuse.config.ts")
        assert.equal(generatedFilesOf(bare)["rootfs/opt/wayuse/htdocs/console/config.json"], undefined)
        const outdir = await mkdtemp(join(tmpdir(), "wayuse-"))
        try {
            const paths = await writeBuildDir(bare, outdir)
            assert.deepEqual(await readdir(join(outdir, "rootfs", DEFAULT_HTDOCS)), [])
            assert.deepEqual(paths.filter(path => path.includes("htdocs")), [])
            const script = await stat(join(outdir, "rootfs/opt/wayuse/bin/supervise.sh"))
            assert.equal(script.mode & 0o111, 0o111)
        } finally {
            await rm(outdir, {recursive: true, force: true})
        }
    })

    it("writes the directory of wayuse anew, and removes nothing else", async () => {
        const bare = resolveConfig({console: false}, "wayuse.config.ts")
        const outdir = await mkdtemp(join(tmpdir(), "wayuse-"))
        try {
            await mkdir(join(outdir, "rootfs/opt/wayuse/htdocs"), {recursive: true})
            await mkdir(join(outdir, "rootfs/etc/other"), {recursive: true})
            await writeFile(join(outdir, "rootfs/opt/wayuse/htdocs/stale"), "")
            await writeFile(join(outdir, "rootfs/etc/other/kept"), "")
            await writeFile(join(outdir, "kept"), "")
            await writeFile(join(outdir, "Dockerfile"), "FROM scratch\n")

            await writeBuildDir(bare, outdir)
            await assert.rejects(stat(join(outdir, "rootfs/opt/wayuse/htdocs/stale")))
            await stat(join(outdir, "rootfs/etc/other/kept"))
            await stat(join(outdir, "kept"))
            assert.match(await readFile(join(outdir, "Dockerfile"), "utf8"), /^# Generated by @wayuse\/build /)
        } finally {
            await rm(outdir, {recursive: true, force: true})
        }
    })

    it("writes into a directory whose parent is not there yet", async () => {
        const bare = resolveConfig({console: false}, "wayuse.config.ts")
        const outdir = await mkdtemp(join(tmpdir(), "wayuse-"))
        try {
            await writeBuildDir(bare, join(outdir, "docker/wayuse"))
            await stat(join(outdir, "docker/wayuse/Dockerfile"))
            await stat(join(outdir, "docker/wayuse/rootfs/opt/wayuse/wayuse.config.json"))
        } finally {
            await rm(outdir, {recursive: true, force: true})
        }
    })

    it("writes the build directory, the scripts executable", async () => {
        const outdir = await mkdtemp(join(tmpdir(), "wayuse-"))
        try {
            await writeBuildDir(config, outdir, {vars: {icon: "🐟", title: "fish & <chips>"}})
            assert.match(await readFile(join(outdir, "Dockerfile"), "utf8"), /^# Generated by @wayuse\/build /)
            const script = await stat(join(outdir, "rootfs/opt/wayuse/bin/supervise.sh"))
            assert.equal(script.mode & 0o111, 0o111)
            const generated = await stat(join(outdir, "rootfs/opt/wayuse/bin/chrome-start.sh"))
            assert.equal(generated.mode & 0o111, 0o111)

            // The console as its URLs lay it out, where the server looks for it by default.
            const console = join(outdir, "rootfs", DEFAULT_HTDOCS, "console")
            assert.match(await readFile(join(console, "index.html"), "utf8"), /<script type="module" src="js\/login\.js">/)
            assert.match(await readFile(join(console, "vnc/index.html"), "utf8"), /<script type="module" src="\.\.\/js\/vnc\.js">/)
            assert.match(await readFile(join(console, "js/login.js"), "utf8"), /from\s*"\.\/console-client\.js"/)
            assert.match(await readFile(join(console, "js/vnc.js"), "utf8"), /from\s*"\.\.\/vendor\/novnc\.js"/)
            assert.match(await readFile(join(console, "js/monitor.js"), "utf8"), /from\s*"\.\.\/vendor\/html-ele\.js"/)

            // The values of console.vars, written into the pages as text.
            const api = await readFile(join(console, "api/index.html"), "utf8")
            assert.match(api, /<title>fish &amp; &lt;chips&gt; API<\/title>/)
            assert.match(api, /<span class="header-icon">🐟<\/span>\n +<span class="header-title">fish &amp; &lt;chips&gt;<\/span>/)

            // What a user of the image replaces: beside the console, empty, and loaded by every page after its own.
            const custom = join(outdir, "rootfs", DEFAULT_HTDOCS, "custom")
            assert.equal(await readFile(join(custom, "styles.css"), "utf8"), "/* styles.css */\n")
            assert.equal(await readFile(join(custom, "script.js"), "utf8"), "/* script.js */\n")
            const entry = await readFile(join(console, "index.html"), "utf8")
            assert.match(entry, /<body id="wayuse-login">/)
            assert.match(entry, /href="css\/console\.css">\n +<link rel="stylesheet" href="\.\.\/custom\/styles\.css">/)
            assert.match(entry, /src="js\/login\.js"><\/script>\n +<script type="module" src="\.\.\/custom\/script\.js">/)
            const monitor = await readFile(join(console, "monitor/index.html"), "utf8")
            assert.match(monitor, /<body id="wayuse-monitor">/)
            assert.match(monitor, /href="\.\.\/css\/console\.css">\n +<link rel="stylesheet" href="\.\.\/\.\.\/custom\/styles\.css">/)
            assert.match(monitor, /src="\.\.\/js\/monitor\.js"><\/script>\n +<script type="module" src="\.\.\/\.\.\/custom\/script\.js">/)
            assert.match(await readFile(join(console, "api/index.html"), "utf8"), /<body id="wayuse-api">/)
            assert.match(await readFile(join(console, "vnc/index.html"), "utf8"), /<body id="wayuse-vnc">/)

            // noVNC as one module for the vnc page, with the notices its license asks to keep.
            const novnc = await readFile(join(console, "vendor/novnc.js"), "utf8")
            assert.match(novnc, /Licensed under MPL 2\.0/)
            assert.match(novnc, /export\s*\{\s*\w+ as default\s*\}/)

            // html-ele under the name the console's scripts import it by.
            const htmlEle = await readFile(join(console, "vendor/html-ele.js"), "utf8")
            assert.match(htmlEle, /export\s*\{[^}]*\bELE\b[^}]*\}/)
        } finally {
            await rm(outdir, {recursive: true, force: true})
        }
    })
})
