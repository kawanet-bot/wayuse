// The scripts beside the Dockerfile that build and run the image without Docker Compose, such as from a systemd unit.

import type {WayuseClient} from "wayuse"
import {HOST_GATEWAY, PUBLISH, SERVICE, SHM_SIZE, VOLUME, VOLUME_TARGET, passedOf} from "./compose.ts"
import {type BuildOptions, PORT} from "./dockerfile.ts"
import {shellDefaultsOf} from "./shell-env.ts"

type Resolved = WayuseClient.Config

const headerOf = (config: Resolved): string =>
    `# Generated by @wayuse/build ${config.wayuse.build.version}. Edit ${config.wayuse.build.config} and build again.`

/**
 * The project's name as Docker Compose makes it of a directory's: lower case, with the other characters left out.
 */
export const projectOf = (dir: string): string => dir.toLowerCase().replace(/[^a-z0-9_-]/g, "").replace(/^[_-]+/, "") || SERVICE

// The names Docker Compose gives the image, the container and the volume, so that either way starts the same image with the same profile.
const imageOf = (options: BuildOptions): string => `${projectOf(options.project ?? SERVICE)}-${SERVICE}`
const containerOf = (options: BuildOptions): string => `${projectOf(options.project ?? SERVICE)}-${SERVICE}-1`
const volumeOf = (options: BuildOptions): string => `${projectOf(options.project ?? SERVICE)}_${VOLUME}`

/**
 * docker-build.sh
 */
export const dockerBuildOf = (config: Resolved, options: BuildOptions = {}): string => `
#!/bin/bash
${headerOf(config)}
# Builds the image of this directory, under the name docker-run.sh starts. The arguments go to docker build as its options.
set -eu

${shellDefaultsOf({WAYUSE_IMAGE: imageOf(options)})}
exec docker build -t "$WAYUSE_IMAGE" "$@" "$(dirname "$0")"
`.trimStart()

/**
 * docker-run.sh
 */
export const dockerRunOf = (config: Resolved, options: BuildOptions = {}): string => `
#!/bin/bash
${headerOf(config)}
# Runs the image in the foreground, for systemd to watch. The arguments go to docker run as its options.
set -eu

# A value in the environment wins, such as one that EnvironmentFile= of a systemd unit gives.
${shellDefaultsOf({WAYUSE_IMAGE: imageOf(options), WAYUSE_PUBLISH: PUBLISH, ...passedOf(config)})}
# The container gets the variables named here alone, so the private key of the .env stays out.
exec docker run --rm --name ${containerOf(options)} \\
    --shm-size ${SHM_SIZE} \\
    --add-host ${HOST_GATEWAY} \\
    -p "$WAYUSE_PUBLISH:${PORT}" \\
${Object.keys(passedOf(config)).map(name => `    -e ${name} \\\n`).join("")}    -v ${volumeOf(options)}:${VOLUME_TARGET} \\
    "$@" \\
    "$WAYUSE_IMAGE"
`.trimStart()
