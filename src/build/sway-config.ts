import type {WayuseClient} from "wayuse"
import {CASCADE_COUNT, CASCADE_STEP} from "../screen/cascade.ts"

type Resolved = WayuseClient.Config

// As many position lines as outputs a container may have: a line for an output that does not exist is ignored.
export const MAX_OUTPUTS = 8

// Beyond the farthest step of a window, for its shadow.
const SHADOW = 32

// Room for a window of the widest screen at its farthest step, so it would not show on the next output.
const pitchOf = (maxWidth: number): number => Math.ceil((maxWidth + CASCADE_STEP * CASCADE_COUNT + SHADOW) / 64) * 64

/**
 * The sway configuration: the outputs side by side, every window floating.
 */
export const swayConfigOf = (config: Resolved): string => {
    const {width, height, maxWidth} = config.screen

    const pitch = pitchOf(maxWidth)
    const positions = Array.from({length: MAX_OUTPUTS}, (_, i) => `output HEADLESS-${i + 1} position ${i * pitch} 0`)

    return `
# Generated by @wayuse/build ${config.wayuse.build.version}. Edit ${config.wayuse.build.config} and build again.

output * resolution ${width}x${height}
${positions.join("\n")}

default_border none

# A tiled second window, a popup for one, would split the output and shrink the page.
for_window [app_id="^google-chrome"] floating enable

# A window may be larger than its output, to capture a page at the size asked for.
floating_maximum_size -1 x -1
`.trimStart()
}
