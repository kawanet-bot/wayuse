// The compose file beside the Dockerfile, for the compose file of a project to include.

import type {WayuseClient} from "wayuse"
import {PORT} from "./dockerfile.ts"

type Resolved = WayuseClient.Config

/** The service of compose.yml, after which Docker Compose names the image. */
export const SERVICE = "wayuse"

/** The volume of compose.yml, which keeps Chrome's profile. */
export const VOLUME = "wayuse_config"

/** Where the container has the volume. */
export const VOLUME_TARGET = "/home/wayuse/.config"

/** sway dies of a bus error on the 64MB Docker gives by default. */
export const SHM_SIZE = "256m"

/** The host's name, for a server on the host. */
export const HOST_GATEWAY = "host.docker.internal:host-gateway"

/** Where the port is published unless WAYUSE_PUBLISH says otherwise: on this host alone. */
export const PUBLISH = `127.0.0.1:${PORT}`

const headerOf = (config: Resolved): string =>
    `# Generated by @wayuse/build ${config.wayuse.build.version}. Edit ${config.wayuse.build.config} and build again.`

// The characters of a User-Agent, base64 and URLs, which Compose takes as they are in a default. Left empty, the value baked into the image applies.
const defaultOf = (value: string | undefined): string => value != null && /^[A-Za-z0-9 ._~+=\/(),;:?#-]*$/.test(value) ? value : ""

/**
 * The variables the container reads, each with the value the image has.
 */
export const passedOf = (config: Resolved): Record<string, string> => ({
    WAYUSE_SCREEN_OUTPUTS: String(config.screen.outputs),
    ...(config.apps.chrome && {WAYUSE_USER_AGENT: defaultOf(config.apps.chrome.env.WAYUSE_USER_AGENT)}),
    // The key is given to each container, and the server has its own default audience. One that checks no token refuses a key.
    ...(config.auth !== false && {WAYUSE_JWT_PUBLIC_KEY: "", WAYUSE_JWT_AUDIENCE: ""}),
})

/**
 * compose.yml
 */
export const composeOf = (config: Resolved): string => `
${headerOf(config)}
# Include it from the project's compose file. Run alone, it misses the project's .env.

volumes:
  # Chrome's profile outlives the image.
  ${VOLUME}:

services:
  ${SERVICE}:
    build:
      context: "."
    # sway dies of a bus error on the 64MB Docker gives by default.
    shm_size: "${SHM_SIZE}"
    extra_hosts:
      # A server on this host is http://host.docker.internal:<port>/
      - "${HOST_GATEWAY}"
    ports:
      # Reached from this host alone, unless .env says otherwise: WAYUSE_PUBLISH=0.0.0.0:${PORT}
      - "\${WAYUSE_PUBLISH:-${PUBLISH}}:${PORT}"
    environment:
      # A value in .env or the shell wins.
${Object.entries(passedOf(config)).map(([name, value]) => `      ${name}: ${JSON.stringify(`\${${name}:-${value}}`)}`).join("\n")}
    volumes:
      - "${VOLUME}:${VOLUME_TARGET}"
`.trimStart()
